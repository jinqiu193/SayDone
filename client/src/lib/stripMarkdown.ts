/**
 * 把 AI 输出里的 markdown 标记剥离成纯文本。
 *
 * 设计目标：把**任何**潜在 markdown 标记清理干净，避免在不支持 markdown 渲染的目标
 * （如终端、IDE、纯文本聊天框、某些 IM、移动端输入框）显示成 `**加粗**`、`# 标题`、
 * ```代码围栏``` 等"乱码"。
 *
 * 设计取舍：
 * - 优先剥装饰性标记（粗体/斜体/标题/列表前缀/引用前缀/分隔线），保留可见文字
 * - 行内代码 `` ` `` 去掉反引号但**保留代码内容**
 * - 代码围栏 ```...``` **完全去掉**（含内部内容）— AI 输出里围栏通常是噪音示例
 * - 链接 `[text](url)` 保留 `text`，丢弃 `url`（避免长 URL 在粘贴时被某些应用转义乱码）
 * - 图片 `![alt](url)` 保留 `alt`，丢弃 `url`
 * - HTML 标签全部去掉（包括 onerror 等危险，但这里只输入来自受信任的本地 LLM）
 * - 多余连续空行合并成单个 `\n`
 * - 行尾空白去掉
 */

export function stripMarkdown(input: string): string {
  if (!input) return ''
  let s = input

  // 1. 代码围栏（含多行）— 完全删除
  s = s.replace(/```[\s\S]*?(?:```|$)/g, '')

  // 2. 标题前缀（# 到 ######） — 行首去标记
  s = s.replace(/^[ \t]*#{1,6}[ \t]+/gm, '')

  // 3. 引用前缀 `> ` (可能多层：>> 、 >>>) — 行首去掉
  s = s.replace(/^[ \t]*>+/gm, '')

  // 4. 列表前缀：`- `、`* `、`+ `、`1. `、`1) ` — 行首去掉
  //    注意 `*` 既做列表也做 italic，先剥列表（只匹配行首后跟空格）
  s = s.replace(/^[ \t]*([-*+])[ \t]+/gm, '')
  s = s.replace(/^[ \t]*\d+[.)][ \t]+/gm, '')

  // 5. 分隔线（--- 或 ***）单独成行 — 删除整行
  s = s.replace(/^[ \t]*([-*_]){3,}[ \t]*$/gm, '')

  // 6. 图片 `![alt](url)` — 保留 alt，丢弃 url
  s = s.replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')

  // 7. 链接 `[text](url)` — 保留 text，丢弃 url
  //    防御：text 里可能含嵌套括号，简化为 [^)]*
  s = s.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')

  // 8. 引用式链接 `[text][ref]` — 简化：去掉整个
  s = s.replace(/\[([^\]]*)\]\[[^\]]*\]/g, '$1')

  // 9. 粗体/斜体 — 多种语法
  //    `**text**` → `text`
  //    `__text__` → `text`
  //    `*text*` / `_text_` → `text`（注意不要匹配列表项余下的 *）
  //    顺序：先匹配 `**`**`、**`__`**`，再匹配单星/单下划线
  s = s.replace(/\*\*([^*]+)\*\*/g, '$1')
  s = s.replace(/__([^_]+)__/g, '$1')
  // 单星/单下划线 — 单词边界友好（不匹配跨行）
  s = s.replace(/(?<![*\w])\*([^*\n]+)\*(?!\w)/g, '$1')
  s = s.replace(/(?<![_\w])_([^_\n]+)_(?!\w)/g, '$1')

  // 10. 行内代码 `` `code` `` — 去掉反引号但保留内容
  s = s.replace(/`+([^`\n]+)`+/g, '$1')

  // 11. 删除线 ~~text~~ → text
  s = s.replace(/~~([^~]+)~~/g, '$1')

  // 12. 简单 HTML 标签 — `<tag>...</tag>` 或单标签 `<tag/>`
  s = s.replace(/<[^>]+>/g, '')

  // 13. 转义字符 — 移除反斜杠转义（`\*`、`\[` 等）保留字符本身
  s = s.replace(/\\([\\`*_{}[\]()#+\-.!])/g, '$1')

  // 14. 表格 `|---|` 行 — 删除
  s = s.replace(/^[ \t]*\|?[ :|-]+\|?[ \t]*$/gm, '')

  // 15. 表格分隔 — 简化：去掉单独 `|` 周围的装饰
  //    （不强求完美；表格在不支持 markdown 时基本总会乱，best-effort）

  // 16. 行尾空白
  s = s.replace(/[ \t]+(?=\n|$)/g, '')

  // 17. 连续空行（3+）合并为单个 \n
  s = s.replace(/\n{3,}/g, '\n\n')

  // 18. 头尾空白
  s = s.trim()

  return s
}
